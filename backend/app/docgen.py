"""Layer A: synthetic document factory. Renders real PDF files from a ground-truth dataset (synthetic.build_dataset).

Output is deterministic (reportlab invariant mode): regenerating from the same dataset gives byte-identical files.
Every page carries a synthetic/demo banner. Fonts are the PDF base fonts, so amounts are printed as plain INR
figures (no rupee glyph), as bank and GST documents usually do.
"""

from pathlib import Path
from typing import Any

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

BANNER = "SYNTHETIC DEMO DOCUMENT - FICTIONAL DATA - NOT A REAL FINANCIAL RECORD"
INK, TEAL, LINE = colors.HexColor("#163247"), colors.HexColor("#11766F"), colors.HexColor("#D9E3E7")
_styles = getSampleStyleSheet()
H1 = ParagraphStyle("h1", parent=_styles["Heading1"], fontSize=14, textColor=INK, spaceAfter=2)
H2 = ParagraphStyle("h2", parent=_styles["Heading2"], fontSize=10.5, textColor=TEAL, spaceBefore=10, spaceAfter=4)
BODY = ParagraphStyle("body", parent=_styles["BodyText"], fontSize=9.5, leading=14, textColor=INK)
SMALL = ParagraphStyle("small", parent=BODY, fontSize=8, textColor=colors.HexColor("#5E707B"))


def inr(n: int | float) -> str:
    """Indian digit grouping with paise, e.g. 1234567 -> 12,34,567.00"""
    whole = abs(int(round(n)))
    s = str(whole)
    head, tail = s[:-3], s[-3:]
    groups = []
    while len(head) > 2:
        groups.insert(0, head[-2:])
        head = head[:-2]
    if head:
        groups.insert(0, head)
    return ("-" if n < 0 else "") + ",".join(groups + [tail]) + ".00"


def dmy(iso: str) -> str:
    y, m, d = iso.split("-")
    return f"{d}-{m}-{y}"


def month_name(ym: str) -> str:
    names = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October",
             "November", "December"]
    return f"{names[int(ym[5:]) - 1]} {ym[:4]}"


def _page(canvas: Any, doc: Any) -> None:
    canvas.saveState()
    canvas.setFillColor(colors.HexColor("#B87925"))
    canvas.setFont("Helvetica-Bold", 7.5)
    canvas.drawCentredString(A4[0] / 2, A4[1] - 22, BANNER)
    canvas.setFillColor(colors.HexColor("#5E707B"))
    canvas.setFont("Helvetica", 7)
    canvas.drawString(36, 20, "Generated by the LoanKart.ai synthetic document factory. All names and numbers are invented.")
    canvas.drawRightString(A4[0] - 36, 20, f"Page {doc.page}")
    canvas.restoreState()


def write_pdf(path: Path, title: str, story: list[Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    doc = SimpleDocTemplate(str(path), pagesize=A4, invariant=1, title=title, author="LoanKart.ai synthetic factory",
                            leftMargin=36, rightMargin=36, topMargin=40, bottomMargin=36)
    doc.build(story, onFirstPage=_page, onLaterPages=_page)


def kv(rows: list[tuple[str, Any]]) -> Table:
    """Label/value block. Values that are ints are printed as INR amounts."""
    data = [[label, inr(value) if isinstance(value, int) and not isinstance(value, bool) else str(value)]
            for label, value in rows]
    table = Table(data, colWidths=[200, 320], hAlign="LEFT")
    table.setStyle(TableStyle([("FONTSIZE", (0, 0), (-1, -1), 9), ("TEXTCOLOR", (0, 0), (0, -1), colors.HexColor("#5E707B")),
                               ("TEXTCOLOR", (1, 0), (1, -1), INK), ("LINEBELOW", (0, 0), (-1, -1), 0.25, LINE),
                               ("TOPPADDING", (0, 0), (-1, -1), 3), ("BOTTOMPADDING", (0, 0), (-1, -1), 3)]))
    return table


def grid(head: list[str], rows: list[list[Any]], widths: list[int], right_from: int = 2) -> Table:
    table = Table([head] + rows, colWidths=widths, repeatRows=1, hAlign="LEFT")
    table.setStyle(TableStyle([("FONTSIZE", (0, 0), (-1, -1), 7.5), ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                               ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#E9F4F1")), ("TEXTCOLOR", (0, 0), (-1, -1), INK),
                               ("GRID", (0, 0), (-1, -1), 0.25, LINE), ("ALIGN", (right_from, 0), (-1, -1), "RIGHT"),
                               ("TOPPADDING", (0, 0), (-1, -1), 2.5), ("BOTTOMPADDING", (0, 0), (-1, -1), 2.5)]))
    return table


def _head(issuer: str, title: str, sub: str = "") -> list[Any]:
    out: list[Any] = [Paragraph(issuer, H1), Paragraph(title, H2)]
    if sub:
        out.append(Paragraph(sub, SMALL))
    out.append(Spacer(1, 6))
    return out


def generate_pack(dataset: dict[str, Any], out_dir: Path) -> list[dict[str, str]]:
    """Write every document for a dataset. Returns the manifest (one entry per PDF)."""
    manifest: list[dict[str, str]] = []
    profile, entity, bank = dataset["profile"], dataset["entity"], dataset["bank"]
    owner, business = profile["borrower_name"], profile["business_name"]
    missing = set(dataset["missing_documents"])

    def emit(stem: str, doc_type: str, group: str, title: str, period: str, story: list[Any]) -> None:
        write_pdf(out_dir / f"{stem}.pdf", title, story)
        manifest.append({"stem": stem, "doc_type": doc_type, "group": group, "title": title, "period": period,
                         "filename": f"{stem}.pdf"})

    for st in bank["statements"]:
        ym, txns = st["month"], st["transactions"]
        last_day = txns[-1]["date"][-2:] if txns else "28"
        story = _head(bank["name"], "STATEMENT OF ACCOUNT", f"Branch: {bank['branch']} | IFSC: {bank['ifsc']}")
        story.append(kv([
            ("Account holder", f"{business} (Prop. {owner})"), ("Account number", bank["account_no"]),
            ("Account type", "Current account"), ("Statement period", f"01-{ym[5:]}-{ym[:4]} to {last_day}-{ym[5:]}-{ym[:4]}"),
            ("Statement month", ym), ("Opening balance", st["opening_balance"]),
            ("Total credits", sum(t["credit"] for t in txns)), ("Total debits", sum(t["debit"] for t in txns)),
            ("Closing balance", st["closing_balance"])]))
        story.append(Spacer(1, 8))
        rows = [[dmy(t["date"]), t["narration"], t["ref"], inr(t["debit"]) if t["debit"] else "",
                 inr(t["credit"]) if t["credit"] else "", inr(t["balance"])] for t in txns]
        story.append(grid(["Date", "Narration", "Ref no", "Debit (INR)", "Credit (INR)", "Balance (INR)"], rows,
                          [52, 222, 62, 60, 60, 66], right_from=3))
        emit(f"bank_statement_{ym}", "bank_statement", "Banking", f"Bank statement, {month_name(ym)}", ym, story)

    for r in dataset["gst"]["returns"]:
        ym = r["month"]
        ident = [("GSTIN", entity["gstin"]), ("Legal name", owner), ("Trade name", business),
                 ("Tax period", month_name(ym)), ("Return month", ym)]
        status = "Filed on time" if not r["days_late"] else f"Filed {r['days_late']} days after the due date"
        story = _head("Goods and Services Tax (synthetic return)", "FORM GSTR-3B", "Monthly summary return")
        story.append(kv(ident + [
            ("3.1(a) Outward taxable supplies", r["taxable"]), ("Integrated tax", r["igst"]),
            ("Central tax", r["cgst"]), ("State tax", r["sgst"]), ("Total tax liability", r["tax"]),
            ("Input tax credit availed", r["itc"]), ("Tax paid in cash", r["net_cash"]),
            ("Due date", dmy(r["due"])), ("Date of filing", dmy(r["filed"])), ("Filing status", status),
            ("Days late", str(r["days_late"])), ("Late fee", r["late_fee"]), ("ARN", r["arn"])]))
        emit(f"gstr3b_{ym}", "gstr3b", "GST", f"GSTR-3B, {month_name(ym)}", ym, story)

        story = _head("Goods and Services Tax (synthetic return)", "FORM GSTR-1", "Statement of outward supplies")
        story.append(kv(ident + [
            ("B2B invoices (count)", str(r["b2b_count"])), ("B2B taxable value", r["b2b_value"]),
            ("B2C taxable value", r["b2c_value"]), ("Total taxable value", r["taxable"]),
            ("Total tax", r["tax"]), ("Due date", dmy(r["gstr1_due"])), ("Date of filing", dmy(r["gstr1_filed"])),
            ("ARN", r["arn"].replace("AA", "AB"))]))
        emit(f"gstr1_{ym}", "gstr1", "GST", f"GSTR-1, {month_name(ym)}", ym, story)

    for itr in dataset["itr"]:
        fy_end = int(itr["ay"][:4])
        story = _head("Income Tax Department (synthetic acknowledgement)",
                      "INDIAN INCOME TAX RETURN ACKNOWLEDGEMENT", "Form ITR-4 summary")
        story.append(kv([
            ("Name", owner), ("PAN", entity["pan"]), ("Assessment year", itr["ay"]),
            ("Gross receipts from business", itr["gross_receipts"]),
            ("Net profit from business", itr["net_income"]), ("Gross total income", itr["net_income"]),
            ("Total tax paid", max(0, round((itr["net_income"] - 400_000) * 0.08))),
            ("Date of filing", f"2{fy_end % 10 + 1}-07-{fy_end}"),
            ("Acknowledgement number", f"{fy_end}0720{itr['net_income'] % 100000:05d}000")]))
        emit(f"itr_{itr['ay']}", "itr", "Income tax", f"ITR acknowledgement, AY {itr['ay']}", itr["ay"], story)

    with_statement = [loan for loan in dataset["loans"] if loan["status"] == "Active"]
    for loan in with_statement:
        story = _head(loan["lender"], "LOAN ACCOUNT STATEMENT", f"As on {dmy(dataset['as_of'])}")
        story.append(kv([
            ("Borrower", f"{business} (Prop. {owner})"), ("Loan account number", loan["account_no"]),
            ("Product", loan["type"]), ("Security", "Secured" if loan["secured"] else "Unsecured"),
            ("Sanctioned amount", loan["principal"]), ("Rate of interest", f"{loan['rate']:.2f}% p.a. reducing"),
            ("Tenure", f"{loan['tenure']} months"), ("EMI", loan["emi"]), ("Date of disbursal", dmy(loan["disbursed"])),
            ("Instalments paid", f"{loan['paid']} of {loan['tenure']}"),
            ("Instalments remaining", str(loan["remaining"])), ("Principal outstanding", loan["outstanding"]),
            ("Overdue amount", 0)]))
        story.append(Spacer(1, 8))
        rows = [[str(r["month"]), dmy(r["due_date"]), inr(r["emi"]), inr(r["principal"]), inr(r["interest"]),
                 inr(r["closing"]), r["status"]] for r in loan["schedule"] if r["due_date"] <= dataset["as_of"]]
        story.append(grid(["No", "Due date", "EMI", "Principal", "Interest", "Balance", "Status"], rows,
                          [28, 62, 70, 70, 70, 80, 110]))
        emit(f"loan_statement_{loan['key']}", "loan_statement", "Existing loans",
             f"Loan statement, {loan['lender']}", dataset["as_of"][:7], story)

    if with_statement:
        window = [(loan, r) for loan in with_statement for r in loan["schedule"]
                  if dataset["months"][0] <= r["ym"] <= dataset["months"][-1]]
        late = sum(1 for _, r in window if r["days_past_due"])
        story = _head("EMI repayment history", "EMI REPAYMENT TRACK",
                      f"Compiled from lender statements for {month_name(dataset['months'][0])} to "
                      f"{month_name(dataset['months'][-1])}")
        story.append(kv([("Borrower", f"{business} (Prop. {owner})"), ("Instalments due in period", str(len(window))),
                         ("Paid on due date", str(len(window) - late)), ("Returned or paid late", str(late))]))
        story.append(Spacer(1, 8))
        rows = [[loan["account_no"], dmy(r["due_date"]), inr(r["emi"]), dmy(r["paid_date"]), str(r["days_past_due"]),
                 r["status"]] for loan, r in sorted(window, key=lambda x: (x[1]["due_date"], x[0]["account_no"]))]
        story.append(grid(["Loan account", "Due date", "EMI", "Paid on", "Days late", "Status"], rows,
                          [90, 70, 75, 70, 55, 130]))
        emit("repayment_history", "repayment_history", "Existing loans", "EMI repayment history, last 12 months",
             f"{dataset['months'][0]} to {dataset['months'][-1]}", story)

    fin = dataset["financials"]
    statements = [] if not fin else [
        ("pnl", "PROFIT AND LOSS ACCOUNT", f"For the year ended 31-03-2026 (FY {fin['fy']})", [
            ("Revenue from operations", "revenue"), ("Cost of goods sold", "cost_of_goods_sold"),
            ("Gross profit", "gross_profit"), ("Salaries and wages", "salaries"), ("Rent", "rent"),
            ("Power and fuel", "power"), ("Freight and transport", "freight"), ("Interest on loans", "interest"),
            ("Depreciation", "depreciation"), ("Other expenses", "other_expenses"),
            ("Net profit before tax", "net_profit")]),
        ("balance_sheet", "BALANCE SHEET", "As at 31-03-2026", [
            ("Proprietor's capital", "capital"), ("Secured loans", "secured_loans"),
            ("Unsecured loans", "unsecured_loans"), ("Sundry creditors", "creditors"),
            ("Total liabilities", "total_liabilities"), ("Fixed assets (net)", "fixed_assets"),
            ("Stock in trade", "stock"), ("Sundry debtors", "debtors"), ("Bank balance", "bank_balance"),
            ("Cash in hand", "cash_in_hand"), ("Total assets", "total_assets")]),
        ("cash_flow", "CASH FLOW STATEMENT", f"For the year ended 31-03-2026 (FY {fin['fy']})", [
            ("Net profit before tax", "net_profit"), ("Add: depreciation", "depreciation"),
            ("Add: interest on loans", "interest_added_back"),
            ("Less: increase in working capital", "working_capital_increase"),
            ("Net cash from operating activities", "cash_from_operations"),
            ("Purchase of fixed assets", "capital_expenditure"), ("Loans taken during the year", "loans_taken"),
            ("Loan principal repaid", "loan_principal_repaid"), ("Interest paid", "interest_paid"),
            ("Proprietor's drawings", "owner_drawings"), ("Net change in cash and bank", "net_change_in_cash"),
            ("Opening cash and bank", "opening_cash"), ("Closing cash and bank", "closing_cash")]),
    ]
    names = {"pnl": "Profit and loss account", "balance_sheet": "Balance sheet", "cash_flow": "Cash-flow statement"}
    for key, title, sub, lines in statements:
        if key in missing:
            continue
        story = _head(f"{business} (Prop. {owner})", title, sub)
        story.append(kv([("Financial year", fin["fy"]), ("Prepared by", "R. Sundar & Co., Chartered Accountants (fictional)")]
                        + [(label, fin[key][field]) for label, field in lines]))
        story.append(Spacer(1, 6))
        story.append(Paragraph("Amounts in INR. Compiled from books of account; unaudited.", SMALL))
        emit(key, key, "Financial statements", f"{names[key]}, FY {fin['fy']}", fin["fy"], story)

    rej = dataset["rejection"]
    if rej:
        story = _head(rej["lender"], "COMMUNICATION OF LOAN APPLICATION DECISION")
        story.append(kv([("Date", dmy(rej["date"])), ("Reference", rej["ref"]),
                         ("Applicant", f"{business} (Prop. {owner})"), ("Product applied for", rej["product"]),
                         ("Amount applied for", rej["amount"])]))
        story.append(Spacer(1, 10))
        story.append(Paragraph("Dear Applicant,", BODY))
        story.append(Paragraph("Thank you for your application. After assessing the information and documents "
                               "submitted, we regret that we are unable to approve the facility at this time.", BODY))
        story.append(Paragraph(f"Reason communicated: {rej['reason']}", BODY))
        story.append(Paragraph("This letter does not prevent you from applying again with updated information.", BODY))
        story.append(Spacer(1, 14))
        story.append(Paragraph("Credit Operations (fictional signatory)", BODY))
        emit("rejection_letter", "rejection_letter", "Rejection", f"Rejection letter, {rej['lender']}",
             rej["date"][:7], story)

    story = _head("Ministry of MSME (synthetic certificate)", "UDYAM REGISTRATION CERTIFICATE")
    story.append(kv([("Udyam registration number", entity["udyam_no"]), ("Name of enterprise", business),
                     ("Type of enterprise", "Micro"), ("Type of organisation", "Proprietary"), ("Owner name", owner),
                     ("Date of commencement of business", dmy(entity["commenced"])),
                     ("Major activity", entity["activity"]), ("Official address", entity["address"])]))
    emit("udyam_certificate", "udyam_certificate", "Business proof", "Udyam registration certificate",
         entity["commenced"][:7], story)

    if dataset["gst"]["registered"]:
        story = _head("Goods and Services Tax (synthetic certificate)", "REGISTRATION CERTIFICATE - FORM GST REG-06")
        story.append(kv([("GSTIN", entity["gstin"]), ("Legal name", owner), ("Trade name", business),
                         ("Constitution of business", "Proprietorship"),
                         ("Date of registration", dmy(entity["gst_registered_on"])),
                         ("Principal place of business", entity["address"])]))
        emit("gst_certificate", "gst_certificate", "Business proof", "GST registration certificate",
             entity["gst_registered_on"][:7], story)

    col = dataset["collateral"]
    if col:
        story = _head("Sri Vinayaga Valuers (fictional)", "VALUATION REPORT")
        story.append(kv([("Owner", owner), ("Asset type", col["type"].replace("_", " ").capitalize()),
                         ("Description", col["description"]), ("Assessed market value", col["value"]),
                         ("Date of valuation", "15-10-2026"), ("Encumbrance noted", "None")]))
        emit("collateral_valuation", "collateral_valuation", "Security", "Collateral valuation report", "2026-10",
             story)

    return manifest
